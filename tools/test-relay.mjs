import assert from 'node:assert/strict';
import { RelayRoute, RELAY_ROUTE } from '../src/survivor/mode/relay-route.ts';
const route=new RelayRoute();
const shortcut=new RelayRoute();
assert.equal(shortcut.update(0,24,100,false),true,'Shortcuts are allowed');
assert.equal(shortcut.atTower,true);assert.equal(shortcut.outcome,null,'Shortcut still requires the boss');
for(const point of RELAY_ROUTE) assert.equal(route.update(point.x,point.z,100,false),true);
assert.equal(route.atTower,true);
assert.equal(route.outcome,null,'Reaching the tower alone cannot win');
route.update(0,24,100,true);assert.equal(route.outcome,'victory');
route.update(0,24,0,false);assert.equal(route.outcome,'victory','Results are terminal');
const death=new RelayRoute();death.update(21,-19,0,false);
assert.equal(death.outcome,'defeat');assert.equal(death.step,0);
const healing=new RelayRoute();
assert.equal(healing.heal(-24,-23,100,100),0);assert.equal(healing.healingUsed,false);
assert.equal(healing.heal(0,0,40,100),0);
assert.equal(healing.heal(-24,-23,40,100),60);
assert.equal(healing.heal(-24,-23,20,100),0,'Healing is single use');
const dead=new RelayRoute();assert.equal(dead.heal(-24,-23,0,100),0,'Pickup cannot revive a defeated player');
console.log('Relay route: approach, boss requirement, terminal outcomes and healing passed.');
