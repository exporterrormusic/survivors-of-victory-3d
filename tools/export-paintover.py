"""Encode the unmodified generated paint-over sheets as runtime WebP textures."""
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = root / 'assets/environment-source/paintover-v1'
output = root / 'public/environment/paintover-v1'
output.mkdir(parents=True, exist_ok=True)
assets = []
for name in ['defenses', 'mechanisms', 'environment', 'barriers', 'paving', 'woodland']:
    original = source / f'{name}-painted.png'
    if not original.exists():
        continue
    image = Image.open(original)
    target = output / f'{name}.webp'
    image.save(target, 'WEBP', quality=96, method=6, exact=True)
    assets.append({'name': name, 'source': str(original.relative_to(root)),
                   'runtime': str(target.relative_to(root)), 'width': image.width,
                   'height': image.height, 'bytes': target.stat().st_size})
    print(name, image.size, target.stat().st_size)
(source / 'assets.json').write_text(json.dumps({'mode': 'built-in image_gen', 'assets': assets}, indent=2) + '\n', encoding='utf8')
capture = json.loads((source / 'projections.json').read_text(encoding='utf8'))
projections = {}
for atlas, rows in capture['atlases'].items():
    for row, item in enumerate(rows):
        projections[item['name']] = {'atlas': atlas, 'row': row, 'rows': len(rows),
                                     **{key: value for key, value in item.items() if key != 'name'}}
(root / 'src/paintover-data.ts').write_text('// Generated by tools/export-paintover.py from the geometry captures.\n'
    + 'export const PAINTOVER_PROJECTIONS = ' + json.dumps(projections, indent=2) + ' as const;\n', encoding='utf8')
