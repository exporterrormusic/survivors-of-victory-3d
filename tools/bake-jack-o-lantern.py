"""Bake a hollow carved pumpkin without runtime boolean operations.
Requires numpy + shapely. Front triangles are clipped in XY, retaining their
surface interpolation; every cut edge receives a real inner-rind wall.
"""
import json
from pathlib import Path
import numpy as np
from shapely.geometry import Polygon, box
from shapely.ops import unary_union, triangulate

root = Path(__file__).resolve().parents[1]
eyes = [Polygon([(-.34,.49),(-.12,.49),(-.22,.67)]), Polygon([(.12,.49),(.34,.49),(.22,.67)]), Polygon([(-.065,.395),(.065,.395),(0,.49)])]
grin = Polygon([(-.35,.37),(-.25,.21),(0,.155),(.25,.21),(.35,.37),(.16,.32),(-.16,.32)])
for x,y,w,h in [(-.115,.32,.075,.14),(.15,.32,.065,.10),(.035,.17,.065,.095)]:
    grin = grin.difference(box(x-w/2,y-h/2,x+w/2,y+h/2))
holes = unary_union(eyes+[grin])

def surface(t, v):
    y=np.cos(v);r=np.sin(v);rib=1+.075*np.cos(t*10)+.015*np.sin(t*3)
    return np.array([np.cos(t)*r*.55*rib, .43+y*.405-(.075*((y-.65)/.35)**2 if y>.65 else 0), np.sin(t)*r*.49*rib])

vertices=[];faces=[];lookup={}
def vertex(p):
    key=tuple(np.round(p,7))
    if key not in lookup: lookup[key]=len(vertices);vertices.append(np.array(p))
    return lookup[key]
def add_triangle(points):
    if np.linalg.norm(np.cross(points[1]-points[0],points[2]-points[0]))<1e-10:return
    ids=[vertex(p) for p in points]
    # Standard outward winding here; Babylon winding is reversed during export.
    centroid=sum(points)/3-np.array([0,.43,0])
    if np.dot(np.cross(points[1]-points[0],points[2]-points[0]),centroid)<0:ids.reverse()
    faces.append(ids)

for row in range(32):
    for col in range(80):
        corners=[surface((col+c)*2*np.pi/80,(row+r)*np.pi/32) for c,r in [(0,0),(1,0),(1,1),(0,1)]]
        for ids in [(0,1,2),(0,2,3)]:
            points=np.array([corners[i] for i in ids]);poly=Polygon(points[:,:2])
            if points[:,2].mean()>=0 or poly.area<1e-10 or not poly.intersects(holes):
                add_triangle(points);continue
            clipped=poly.difference(holes)
            if clipped.is_empty:continue
            matrix=np.vstack([points[:,:2].T,np.ones(3)])
            inverse=np.linalg.inv(matrix)
            for piece in ([clipped] if clipped.geom_type=='Polygon' else clipped.geoms):
                if piece.geom_type!='Polygon':continue
                for triangle in triangulate(piece):
                    if not piece.covers(triangle.representative_point()):continue
                    out=[]
                    for x,y in list(triangle.exterior.coords)[:3]:
                        weights=inverse@np.array([x,y,1]);out.append(weights@points)
                    add_triangle(out)

outer=np.array(vertices);normal=np.zeros_like(outer);edges={}
for a,b,c in faces:
    n=np.cross(outer[b]-outer[a],outer[c]-outer[a])
    for i in [a,b,c]:normal[i]+=n
    for i,j in [(a,b),(b,c),(c,a)]:edges.setdefault(tuple(sorted((i,j))),[]).append((i,j))
normal/=np.maximum(1e-12,np.linalg.norm(normal,axis=1,keepdims=True))
# Keep the XY carving outline aligned through the rind so the small mouth/teeth
# stay open at the gameplay camera angle rather than closing behind a scaled lip.
inner=(outer-np.array([0,.43,0]))*np.array([.98,.98,.84])+np.array([0,.43,0])
positions=[];normals=[];uvs=[];colors=[];indices=[]
def push(p,n,flesh=False):
    theta=np.arctan2(p[2],p[0]);groove=.86+.14*(.5+.5*np.cos(theta*10))
    positions.extend(p);normals.extend(n);uvs.extend([theta/(2*np.pi)+.5,p[1]/.84])
    colors.extend([1.08,1.4,1.8,1] if flesh else [groove,groove,groove,1])
for p,n in zip(outer,normal):push(p,n)
for p,n in zip(inner,-normal):push(p,n,True)
count=len(outer)
for a,b,c in faces:indices.extend([a,c,b,count+a,count+b,count+c])
for occurrences in edges.values():
    if len(occurrences)!=1:continue
    a,b=occurrences[0];points=[outer[a],inner[a],inner[b],outer[b]]
    n=np.cross(points[1]-points[0],points[2]-points[0]);n/=max(1e-12,np.linalg.norm(n))
    start=len(positions)//3
    for p in points:push(p,n,True)
    indices.extend([start,start+2,start+1,start,start+3,start+2])
data={k:[round(float(x),6) for x in v] for k,v in dict(positions=positions,normals=normals,uvs=uvs,colors=colors).items()}
data['indices']=indices
target=root/'src/survivor/jack-o-lantern-geometry.ts'
target.write_text('// Generated by tools/bake-jack-o-lantern.py; do not edit by hand.\nexport const pumpkinGeometry='+json.dumps(data,separators=(',',':'))+';\n')
print(f'Baked {len(indices)//3} triangles, {len(positions)//3} vertices, {target.stat().st_size} bytes')
