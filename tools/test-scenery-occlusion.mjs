import assert from 'node:assert/strict';
import { NullEngine, Scene, FreeCamera, Vector3, MeshBuilder, Mesh, StandardMaterial, Material, TransformNode, DirectionalLight, ShadowGenerator } from '@babylonjs/core';
import { SceneryOcclusion } from '../src/survivor/scenery-occlusion.ts';
const engine=new NullEngine(),scene=new Scene(engine);
const camera=new FreeCamera('camera',new Vector3(0,2,-10),scene);scene.activeCamera=camera;camera.setTarget(new Vector3(0,1,0));camera.getViewMatrix(true);
const material=new StandardMaterial('shared-foliage',scene);material.transparencyMode=Material.MATERIAL_ALPHATEST;
const wall=MeshBuilder.CreateBox('occluder',{width:3,height:5,depth:1},scene);wall.position.set(0,2,-4);wall.material=material;wall.isPickable=false;
const clear=MeshBuilder.CreateBox('clear',{size:2},scene);clear.position.set(8,2,-4);clear.material=material;
const behind=MeshBuilder.CreateBox('behind-player',{size:2},scene);behind.position.set(0,2,5);behind.material=material;
const shadows=new ShadowGenerator(256,new DirectionalLight('sun',new Vector3(0,-1,0),scene));
const fader=new SceneryOcclusion(scene,shadows),player=Vector3.Zero();
const step=()=>{for(let i=0;i<30;i++)fader.update(1/60,player,[wall,clear,behind]);};
const stalledFader=new SceneryOcclusion(scene);
stalledFader.update(2,player,[wall,clear,behind]);
assert.ok(wall.visibility>.92,'a stalled frame cannot skip the smooth fade');
stalledFader.dispose();
fader.update(1/60,player,[wall,clear,behind]);
assert.ok(wall.visibility>.97,'fade starts gently instead of dropping opacity abruptly');
step();assert.ok(wall.visibility<.17,'non-pickable blocking scenery becomes mostly transparent');
assert.equal(clear.visibility,1,'unobstructing mesh sharing the material stays opaque');
assert.equal(behind.visibility,1,'objects behind the player do not fade');
assert.equal(material.needAlphaBlendingForMesh(wall),true,'faded scenery uses a continuous transparent silhouette');
assert.ok(wall.visibility>=.10&&wall.visibility<.11,'faded silhouette retains ten percent opacity');
assert.equal(material.needDepthPrePass,true,'depth prepass suppresses hidden surfaces');assert.ok(material.needAlphaTestingForMesh(wall),'foliage keeps its cutouts');
wall.position.x=8;step();step();step();assert.equal(wall.visibility,1,'opacity restores after view clears');
const parent=new TransformNode('wind-tree',scene);wall.parent=parent;wall.position.set(0,2,-4);parent.scaling.setAll(.5);parent.position.z=-2;
step();assert.ok(wall.visibility<.17,'scaled and parented geometry is tested in world space');
const trim=MeshBuilder.CreateBox('remote-trim',{size:1},scene);trim.position.set(5,4,-4);trim.material=material;
wall.metadata={occlusionGroup:'gate'};trim.metadata={occlusionGroup:'gate'};
for(let i=0;i<30;i++)fader.update(1/60,player,[wall,trim,clear,behind]);
assert.ok(trim.visibility<.17,'all parts of a blocked prop fade together');
assert.equal(clear.visibility,1,'unrelated props stay opaque');
assert.equal(wall.visibility,trim.visibility,'every part uses exactly one group fade value');
wall.position.x=20;
for(let i=0;i<90;i++){
  fader.update(1/60,player,[wall,trim,clear,behind]);
  assert.equal(wall.visibility,trim.visibility,'parts restore together on every frame');
}
assert.equal(wall.visibility,1);
wall.position.x=0;
for(let i=0;i<30;i++)fader.update(1/60,player,[wall,trim,clear,behind]);
const map=shadows.getShadowMap(),fadedVisibility=wall.visibility;
map.onBeforeBindObservable.notifyObservers(map);
assert.equal(wall.visibility,1,'shadow pass sees the original opaque caster');
assert.equal(material.needAlphaBlendingForMesh(wall),false,'caster stays out of transparent shadow queue');
map.onAfterUnbindObservable.notifyObservers(map);
assert.equal(wall.visibility,fadedVisibility,'camera fade restored after shadow pass');
fader.update(1/60,player,[wall,trim],[wall,trim]);
assert.equal(wall.visibility,1,'entering the elevator exclusion restores opacity immediately');
assert.equal(trim.visibility,1,'all excluded elevator parts stay opaque');
// Only the tower is eligible, even when the elevator body itself blocks the camera.
const liftRoot=new TransformNode('arrival-elevator',scene);
const mast=new TransformNode('elevator-fixed-mast',scene);mast.parent=liftRoot;
const tower=MeshBuilder.CreateBox('tower',{size:2},scene);tower.parent=mast;tower.position.set(0,2,-4);tower.material=material;
tower.metadata={occlusionGroup:mast.uniqueId};
const cage=MeshBuilder.CreateBox('cage',{size:2},scene);cage.parent=liftRoot;cage.position.set(0,1,-3);cage.material=material;
cage.metadata={cameraOcclusionDisabled:true};
for(let i=0;i<30;i++)fader.update(1/60,player,[tower,cage]);
assert.ok(tower.visibility<.17,'obstructing tower fades');
assert.equal(cage.visibility,1,'main elevator never fades with the tower');
tower.position.x=12;
for(let i=0;i<90;i++)fader.update(1/60,player,[tower,cage]);
assert.equal(tower.visibility,1,'blocking cage cannot trigger a clear tower');
assert.equal(cage.visibility,1,'main elevator remains opaque from the side');
const adjacent=MeshBuilder.CreateBox('touching-side-wall',{width:2,height:4,depth:3},scene);
adjacent.position.set(1.65,2,0);adjacent.material=material;
const backWall=MeshBuilder.CreateBox('touching-shrine-front',{width:8,height:5,depth:2},scene);
backWall.position.set(0,2.5,1.5);backWall.material=material;
// A merged doorway's bounding box covers the player, but its geometry does not.
const left=MeshBuilder.CreateBox('left-post',{width:1,height:5,depth:1},scene);left.position.set(-3,2.5,-4);
const right=MeshBuilder.CreateBox('right-post',{width:1,height:5,depth:1},scene);right.position.set(3,2.5,-4);
const doorway=Mesh.MergeMeshes([left,right],true,true);doorway.material=material;
for(let i=0;i<90;i++)fader.update(1/60,player,[adjacent,backWall,doorway]);
assert.equal(adjacent.visibility,1,'touching the side does not count as obscuring the player');
assert.equal(backWall.visibility,1,'nearby shrine behind the player stays opaque');
assert.equal(doorway.visibility,1,'empty space inside merged bounds does not trigger fading');
fader.dispose();assert.equal(wall.visibility,1);assert.equal(material.needAlphaBlendingForMesh(wall),false,'material behavior restored on disposal');
scene.dispose();engine.dispose();console.log('Scenery occlusion: obstruction, clear/behind exclusions, shared materials, cutout foliage, scaled geometry and restoration passed.');
