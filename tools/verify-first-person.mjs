  new HemisphericLight('light',Vector3.Up(),scene);MeshBuilder.CreateGround('ground',{width:100,height:100},scene);
  const index=await loadChibiIndex(),chibi=await Chibi.load(scene,index.variants[variant]);
  const rig=new TwinStickRig(chibi);const position=Vector3.Zero();
